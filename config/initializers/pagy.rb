# `pagy(scope)` を素で呼んでいる）。したがってここ1箇所を変えれば全画面に効く。
# 今後も画面単位で上書きせず、変更が要るときはこのファイルを直すこと。
#
# ※ pagy 8.x のキーは `:items`（9.x で `:limit` に改称）。Gemfile.lock は 8.6.3。
Pagy::DEFAULT[:items] = 30
