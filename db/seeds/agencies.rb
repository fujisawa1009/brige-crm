definitions.each do |group_code, agency_code, name, has_contact, email_count|
  agency_group = AgencyGroup.find_by(group_code: group_code)
  if agency_group.nil?
    puts "agencies seed: AgencyGroup not found for group_code=#{group_code} (agency_code=#{agency_code}, name=#{name}) — skipped."
    next
  end

  agency = Agency.find_or_create_by!(agency_code: agency_code) do |a|
    a.agency_group = agency_group
    a.name = name
    a.contact_person = has_contact ? "テスト担当者" : nil
    a.electronic_contract_enabled = nil
    a.csv_download_visible = nil
    build_emails.call(agency_code, email_count).each { |attr, value| a.public_send("#{attr}=", value) }
  end

  # BRIDGE_PLUS 商材の販売許可（Laravel: agency->products()->attach 相当）
  agency.products << bridge_plus unless agency.products.exists?(bridge_plus.id)
end

